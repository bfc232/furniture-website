// Helper to create active demo booking campaign
function createSampleCampaign(
  id: string,
  productId: string,
  paidUnits = 3,
  manualUnits = 0,
  minUnits = 5
): BookingCampaign {
  const now = new Date();
  const ends = new Date(now.getTime() + 3.5 * 24 * 60 * 60 * 1000); // 3 days 12 hours left
  const total = paidUnits + manualUnits;
  const status = total >= minUnits ? "THRESHOLD_REACHED" : "OPEN";
  return {
    id,
    product_id: productId,
    status,
    min_units: minUnits,
    booking_window_days: 7,
    paid_units: paidUnits,
    manual_adjustment_units: manualUnits,
    qualifying_units: total,
    window_started_at: now.toISOString(),
    window_ends_at: ends.toISOString(),
    threshold_reached_at: total >= minUnits ? now.toISOString() : null,
    is_current: true,
  };
}

